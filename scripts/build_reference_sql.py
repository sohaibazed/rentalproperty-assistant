"""Build reference/supabase-documents.sql: the text of your reference documents, for Supabase.

Included: every .md file under reference/, and every PDF under reference/leases/ and
reference/llc/. A PDF is skipped when a .md file with the same name sits next to it; use that for
scanned PDFs, whose text layer is missing or unreadable, by writing a transcription.
reference/tenant-screening/ is never included. SSN-like numbers are redacted.

Run with `make reference-sql`, then paste the output file into the Supabase SQL Editor.
"""

import re
import sys
from pathlib import Path

from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1] / "reference"
OUT = ROOT / "supabase-documents.sql"
EXCLUDED_DIR = "tenant-screening"
PDF_DIRS = ("leases", "llc")
QUOTE = "$doc$"

# SSNs (123-45-6789), e.g. the responsible party on Form SS-4. EINs (12-3456789) and filing
# numbers are kept: the chat needs them for tax and LLC questions.
SENSITIVE = re.compile(r"\b\d{3}-\d{2}-\d{4}\b")


def redact(text: str) -> str:
    return SENSITIVE.sub("[REDACTED]", text)


def category(rel: Path) -> str:
    return {"leases": "lease", "llc": "llc"}.get(rel.parts[0], "notes")


def md_title(text: str, rel: Path) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return rel.stem.replace("_", " ")


def pdf_text(path: Path) -> tuple[str, int]:
    reader = PdfReader(path)
    pages = [" ".join((page.extract_text() or "").split()) for page in reader.pages]
    return "\n\n".join(f"[page {i}]\n{text}" for i, text in enumerate(pages, 1)), len(pages)


def collect(root: Path) -> list[dict]:
    docs = []
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        if not path.is_file() or EXCLUDED_DIR in rel.parts:
            continue
        if path.suffix == ".md":
            text = path.read_text()
            docs.append({"path": rel.as_posix(), "category": category(rel),
                         "title": md_title(text, rel), "pages": None, "content": text})
        elif (path.suffix == ".pdf" and rel.parts[0] in PDF_DIRS
              and not path.with_suffix(".md").exists()):
            text, pages = pdf_text(path)
            if not text.replace("[page", "").strip():
                raise SystemExit(f"{rel} has no text layer; write {rel.with_suffix('.md')} "
                                 "with a transcription")
            docs.append({"path": rel.as_posix(), "category": category(rel),
                         "title": rel.stem.replace("_", " "), "pages": pages, "content": text})
    for doc in docs:
        doc["content"] = redact(doc["content"])
    return docs


def literal(value: str) -> str:
    if QUOTE in value:
        raise SystemExit(f"Document text contains {QUOTE}; change QUOTE in this script")
    return f"{QUOTE}{value}{QUOTE}"


def to_sql(docs: list[dict]) -> str:
    rows = ",\n".join(
        f"({literal(d['path'])}, '{d['category']}', {literal(d['title'])}, "
        f"{'null' if d['pages'] is None else d['pages']},\n{literal(d['content'])})"
        for d in docs)
    return (
        "-- Generated by `make reference-sql` from reference/ (tenant-screening/ excluded,\n"
        "-- SSN-like numbers redacted). Contains personal details: this file is git-ignored.\n"
        "-- Run in the Supabase SQL Editor after 0002_reference_documents.sql. Safe to re-run:\n"
        "-- documents are matched by path and updated.\n\n"
        "insert into reference_documents (path, category, title, pages, content) values\n"
        f"{rows}\n"
        "on conflict (path) do update set category = excluded.category, title = excluded.title,\n"
        "  pages = excluded.pages, content = excluded.content, updated_at = now();\n\n"
        "select path, category, title, pages, length(content) as chars\n"
        "from reference_documents order by path;\n"
    )


def main() -> None:
    docs = collect(ROOT)
    if not docs:
        sys.exit("No documents found in reference/")
    OUT.write_text(to_sql(docs))
    OUT.chmod(0o600)
    for d in docs:
        print(f"{d['path']}: {len(d['content']):,} chars")
    print(f"Wrote {OUT.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
